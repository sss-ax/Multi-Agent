"""State-aware token constraints for complete typed semantic Actions."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any, Iterable, Mapping

from .semantic_actions import model_semantic_ops


@dataclass
class ActionConstraint:
    """Hard-mask model output against the active Action grammar.

    Semantic Delta Planner, Solver, and Critic calls use complete token-level
    Schema automata. The compiler remains responsible for semantic validation
    after decoding.
    """

    role: str
    task_type: str
    allowed_ops: tuple[str, ...]
    reason: str
    required_fact_ids: tuple[str, ...] = ()
    fixed_actions: tuple[str, ...] = ()
    schema_mode: str = ""
    allowed_source_refs: tuple[str, ...] = ()
    allowed_choice_labels: tuple[str, ...] = ()
    allowed_citation_refs: tuple[str, ...] = ()
    allowed_repair_actions: tuple[str, ...] = ()
    # For Critic multiple-choice audits these are generated by the kernel from
    # the immutable Solver candidate.  The model may fill verdicts/reasons, but
    # it may not choose the audit scope.
    required_audit_slots: tuple[int, ...] = ()
    required_audit_options: tuple[str, ...] = ()
    required_audit_claim_ids: tuple[str, ...] = ()
    required_audit_elimination_claim_ids: tuple[str, ...] = ()
    required_candidate_version: str = ""
    required_manifest_digest: str = ""
    forbidden_choice_labels: tuple[str, ...] = ()
    required_solver_slots: tuple[int, ...] = ()
    _operation_paths: tuple[tuple[int, ...], ...] = field(default=(), init=False, repr=False)
    _done_path: tuple[int, ...] = field(default=(), init=False, repr=False)
    _schema_transitions: dict[int, dict[int, set[int]]] = field(default_factory=dict, init=False, repr=False)
    _schema_start_state: int = field(default=0, init=False, repr=False)
    _schema_complete_state: int = field(default=-1, init=False, repr=False)
    _schema_content_state: int = field(default=-1, init=False, repr=False)
    _schema_content_filled_state: int = field(default=-1, init=False, repr=False)
    _schema_quote_state: int = field(default=-1, init=False, repr=False)
    _schema_strategy_empty_state: int = field(default=-1, init=False, repr=False)
    _schema_strategy_filled_state: int = field(default=-1, init=False, repr=False)
    _safe_string_token_ids: frozenset[int] = field(default_factory=frozenset, init=False, repr=False)
    _nonspace_string_token_ids: frozenset[int] = field(default_factory=frozenset, init=False, repr=False)
    _schema_prefix_cache: dict[tuple[int, ...], frozenset[int]] = field(default_factory=dict, init=False, repr=False)
    _schema_free_modes: dict[int, str] = field(default_factory=dict, init=False, repr=False)
    _schema_nonspace_destinations: dict[int, int] = field(default_factory=dict, init=False, repr=False)
    _schema_safe_destinations: dict[int, int] = field(default_factory=dict, init=False, repr=False)
    _schema_space_destinations: dict[int, int] = field(default_factory=dict, init=False, repr=False)
    _bound_tokenizer_id: int = field(default=0, init=False, repr=False)

    def as_dict(self) -> dict[str, Any]:
        return {
            "role": self.role,
            "task_type": self.task_type,
            "allowed_ops": list(self.allowed_ops),
            "reason": self.reason,
            "required_fact_ids": list(self.required_fact_ids),
            "fixed_action_count": len(self.fixed_actions),
            "allowed_source_refs": list(self.allowed_source_refs),
            "allowed_choice_labels": list(self.allowed_choice_labels),
            "allowed_citation_refs": list(self.allowed_citation_refs),
            "allowed_repair_actions": list(self.allowed_repair_actions),
            "required_audit_slots": list(self.required_audit_slots),
            "required_audit_options": list(self.required_audit_options),
            "required_audit_claim_ids": list(self.required_audit_claim_ids),
            "required_audit_elimination_claim_ids": list(self.required_audit_elimination_claim_ids),
            "required_candidate_version": self.required_candidate_version,
            "required_manifest_digest": self.required_manifest_digest,
            "forbidden_choice_labels": list(self.forbidden_choice_labels),
            "required_solver_slots": list(self.required_solver_slots),
            "mode": (
                "full-planner-schema"
                if self.schema_mode == "planner_plan"
                else "full-solver-schema" if self.schema_mode.startswith("solver_")
                else "full-critic-schema" if self.schema_mode.startswith("critic_")
                else "fixed-action" if self.fixed_actions else "operation-prefix-constrained"
            ),
        }

    def bind(self, tokenizer: Any) -> None:
        if self._bound_tokenizer_id == id(tokenizer):
            return
        self._bound_tokenizer_id = id(tokenizer)
        if self.schema_mode == "planner_plan":
            self._bind_planner_schema(tokenizer)
            return
        if self.schema_mode.startswith("solver_") or self.schema_mode.startswith("critic_"):
            self._bind_semantic_schema(tokenizer)
            return
        paths: list[tuple[int, ...]] = []
        if self.fixed_actions:
            paths.extend(tuple(self._encode(tokenizer, action)) for action in self.fixed_actions)
        else:
            for op in self.allowed_ops:
                literal = '{"op":"done"}' if op == "done" else f'{{"op":"{op}"'
                paths.append(tuple(self._encode(tokenizer, literal)))
        self._operation_paths = tuple(paths)
        self._done_path = next(
            (path for op, path in zip(self.allowed_ops, paths) if op == "done"),
            (),
        )
        if self.fixed_actions and "done" in self.allowed_ops and paths:
            self._done_path = paths[0]

    def _bind_planner_schema(self, tokenizer: Any) -> None:
        """Compile the canonical Planner Action into a token-level NFA.

        Semantic text remains model-controlled, but structural punctuation,
        field names/order, source references, and the terminal object boundary
        are all generated through explicit transitions.  Free text deliberately
        excludes quotes, backslashes, control characters, and special tokens;
        this keeps every reachable sequence valid JSON without post-hoc repair.

        Model-generated fact ``content`` is one non-empty JSON string.  This is
        the only Planner fact representation accepted by the protocol.
        """
        self._operation_paths = ()
        self._done_path = ()
        self._schema_transitions = {}
        self._schema_prefix_cache = {(): frozenset({0})}
        self._schema_free_modes = {}
        self._schema_nonspace_destinations = {}
        self._schema_safe_destinations = {}
        self._schema_space_destinations = {}
        self._schema_start_state = 0
        self._schema_content_state = 1
        self._schema_content_filled_state = 2
        self._schema_quote_state = 3
        self._schema_strategy_empty_state = 4
        self._schema_strategy_filled_state = 5
        self._schema_complete_state = 6
        next_state = 7

        def add_path(start: int, text: str, end: int) -> None:
            nonlocal next_state
            path = tuple(self._encode(tokenizer, text))
            if not path:
                raise ValueError(f"planner schema literal tokenized to an empty path: {text!r}")
            state = start
            for index, token_id in enumerate(path):
                destination = end if index == len(path) - 1 else next_state
                if index != len(path) - 1:
                    next_state += 1
                self._schema_transitions.setdefault(state, {}).setdefault(token_id, set()).add(destination)
                state = destination

        def add_escapes(start: int, end: int) -> None:
            for escape in ('\\"', "\\\\", "\\/", "\\b", "\\f", "\\n", "\\r", "\\t"):
                add_path(start, escape, end)

        self._schema_free_modes = {
            self._schema_content_state: "required_empty",
            self._schema_content_filled_state: "required_filled",
            self._schema_quote_state: "optional",
            self._schema_strategy_empty_state: "required_empty",
            self._schema_strategy_filled_state: "required_filled",
        }
        self._schema_nonspace_destinations = {
            self._schema_content_state: self._schema_content_filled_state,
            self._schema_strategy_empty_state: self._schema_strategy_filled_state,
        }
        add_escapes(self._schema_content_state, self._schema_content_filled_state)
        add_escapes(self._schema_content_filled_state, self._schema_content_filled_state)
        add_escapes(self._schema_quote_state, self._schema_quote_state)
        add_escapes(self._schema_strategy_empty_state, self._schema_strategy_filled_state)
        add_escapes(self._schema_strategy_filled_state, self._schema_strategy_filled_state)

        numeric = self.task_type in {"numeric_solve", "numeric_comparison"}
        if numeric:
            add_path(0, '{"op":"plan","facts":[{"content":"', self._schema_content_state)
            source_refs = self.allowed_source_refs
            if not source_refs:
                raise ValueError("numeric Planner schema requires at least one visible source reference")
            for source_ref in dict.fromkeys(str(item) for item in source_refs if str(item)):
                suffix = '","source":' + json.dumps(source_ref, ensure_ascii=False) + ',"quote":"'
                add_path(self._schema_content_filled_state, suffix, self._schema_quote_state)
            add_path(self._schema_quote_state, '"},{"content":"', self._schema_content_state)
            add_path(self._schema_quote_state, '"}],"strategy":"', self._schema_strategy_empty_state)
        else:
            add_path(0, '{"op":"plan","facts":[],"strategy":"', self._schema_strategy_empty_state)
        add_path(self._schema_strategy_filled_state, '"}', self._schema_complete_state)

        cached = getattr(tokenizer, "_planner_json_safe_token_cache", None)
        if cached is None:
            try:
                vocab_size = len(tokenizer)
            except TypeError as exc:  # pragma: no cover - real tokenizers implement this
                raise TypeError("full Planner schema decoding requires a sized tokenizer") from exc
            special_ids = set(int(item) for item in getattr(tokenizer, "all_special_ids", ()) or ())
            safe: set[int] = set()
            nonspace: set[int] = set()
            for token_id in range(int(vocab_size)):
                if token_id in special_ids:
                    continue
                try:
                    piece = tokenizer.decode(
                        [token_id],
                        skip_special_tokens=False,
                        clean_up_tokenization_spaces=False,
                    )
                except TypeError:
                    piece = tokenizer.decode([token_id])
                if (
                    not piece
                    or "\ufffd" in piece
                    or '"' in piece
                    or "\\" in piece
                    or any(ord(char) < 0x20 for char in piece)
                ):
                    continue
                safe.add(token_id)
                if piece.strip():
                    nonspace.add(token_id)
            cached = (frozenset(safe), frozenset(nonspace))
            try:
                setattr(tokenizer, "_planner_json_safe_token_cache", cached)
            except (AttributeError, TypeError):
                pass
        self._safe_string_token_ids, self._nonspace_string_token_ids = cached

    def _bind_semantic_schema(self, tokenizer: Any) -> None:
        """Compile a task-specific Solver or Critic Action into a token NFA."""
        self._operation_paths = ()
        self._done_path = ()
        self._schema_transitions = {}
        self._schema_prefix_cache = {(): frozenset({0})}
        self._schema_free_modes = {}
        self._schema_nonspace_destinations = {}
        self._schema_safe_destinations = {}
        self._schema_space_destinations = {}
        self._schema_start_state = 0
        self._schema_complete_state = 1
        next_state = 2

        def state(mode: str = "") -> int:
            nonlocal next_state
            value = next_state
            next_state += 1
            if mode:
                self._schema_free_modes[value] = mode
            return value

        def required_string_states() -> tuple[int, int]:
            empty = state("required_empty")
            filled = state("required_filled")
            self._schema_nonspace_destinations[empty] = filled
            add_escapes(empty, filled)
            add_escapes(filled, filled)
            return empty, filled

        def optional_string_state() -> int:
            value = state("optional")
            add_escapes(value, value)
            return value

        def bounded_string_states(*, required: bool, max_tokens: int) -> tuple[int, tuple[int, ...]]:
            """Return a finite JSON-string automaton and all legal exit states."""
            if max_tokens <= 0:
                raise ValueError("bounded string max_tokens must be positive")
            if not required:
                states = [state() for _ in range(max_tokens + 1)]
                for index in range(max_tokens):
                    current, destination = states[index], states[index + 1]
                    self._schema_free_modes[current] = "optional"
                    self._schema_safe_destinations[current] = destination
                    add_escapes(current, destination)
                return states[0], tuple(states)

            empty = [state() for _ in range(max_tokens + 1)]
            filled = [state() for _ in range(max_tokens + 1)]
            for index in range(max_tokens):
                self._schema_free_modes[empty[index]] = "required_empty"
                self._schema_space_destinations[empty[index]] = empty[index + 1]
                self._schema_nonspace_destinations[empty[index]] = filled[index + 1]
                self._schema_free_modes[filled[index]] = "required_filled"
                self._schema_safe_destinations[filled[index]] = filled[index + 1]
                add_escapes(empty[index], filled[index + 1])
                add_escapes(filled[index], filled[index + 1])
            return empty[0], tuple(filled[1:])

        def add_path_from_many(starts: Iterable[int], text: str, end: int) -> None:
            for start in starts:
                add_path(start, text, end)

        quoted_suffix_ids: set[int] | None = None

        def add_string_close(starts: Iterable[int], end: int) -> None:
            """Close a JSON string, including BPE tokens that merge content+quote."""
            nonlocal quoted_suffix_ids
            starts = tuple(starts)
            add_path_from_many(starts, '\"}', end)
            if quoted_suffix_ids is None:
                quoted_suffix_ids = set()
                for token_id in range(len(tokenizer)):
                    try:
                        piece = tokenizer.decode([token_id], skip_special_tokens=False, clean_up_tokenization_spaces=False)
                    except TypeError:
                        piece = tokenizer.decode([token_id])
                    if piece and piece.endswith('"') and '"' not in piece[:-1] and '\\' not in piece:
                        quoted_suffix_ids.add(token_id)
            for start in starts:
                for token_id in quoted_suffix_ids:
                    middle = state()
                    self._schema_transitions.setdefault(start, {}).setdefault(token_id, set()).add(middle)
                    add_path(middle, '}', end)

        def add_path(start: int, text: str, end: int) -> None:
            nonlocal next_state
            path = tuple(self._encode(tokenizer, text))
            if not path:
                raise ValueError(f"solver schema literal tokenized to an empty path: {text!r}")
            cursor = start
            for index, token_id in enumerate(path):
                destination = end if index == len(path) - 1 else state()
                self._schema_transitions.setdefault(cursor, {}).setdefault(token_id, set()).add(destination)
                cursor = destination

        def add_escapes(start: int, end: int) -> None:
            for escape in ('\\"', "\\\\", "\\/", "\\b", "\\f", "\\n", "\\r", "\\t"):
                add_path(start, escape, end)

        if self.schema_mode == "solver_numeric":
            expression_empty, expression_filled = required_string_states()
            value_empty, value_filled = required_string_states()
            add_path(0, '{"op":"solve_numeric","expression":"', expression_empty)
            add_path(expression_filled, '","value":"', value_empty)
            add_path(value_filled, '"}', self._schema_complete_state)
        elif self.schema_mode == "solver_choice":
            labels = tuple(dict.fromkeys(self.allowed_choice_labels))
            answer_labels = tuple(label for label in labels if label not in set(self.forbidden_choice_labels))
            if not answer_labels:
                raise ValueError("multiple-choice Solver schema requires visible choice labels")
            slot_entry_start = state()
            confidence_start = state()
            review_first = state()
            for label in answer_labels:
                add_path(0, '{"op":"choose_option","answer":' + json.dumps(label) + ',"slot_reasons":[{"slot":', slot_entry_start)
            # A bounded array of slot-level reasons. Selected terms are source
            # derived by the kernel after the model chooses an option.
            required_slots = self.required_solver_slots or tuple(range(1, 13))
            max_slots = len(required_slots)
            previous_reason_ends: tuple[int, ...] = ()
            for slot_index, slot_number in enumerate(required_slots):
                reason_empty, reason_ends = bounded_string_states(required=True, max_tokens=64)
                if slot_index == 0:
                    add_path(slot_entry_start, str(slot_number) + ',"reason":"', reason_empty)
                else:
                    add_path_from_many(previous_reason_ends, '"},{"slot":' + str(slot_number) + ',"reason":"', reason_empty)
                previous_reason_ends = reason_ends
                # Every non-empty prefix of a reason may close the slot array,
                # or continue with the next slot. The final array is followed by
                # the required eliminated-options object.
                close_options_prefix = state()
                if not self.required_solver_slots or slot_index + 1 == len(required_slots):
                    add_path_from_many(reason_ends, '"}],"option_reviews":[', close_options_prefix)
                # Keep the object delimiter as a separate transition. This
                # matters for BPE tokenizers that merge `":{"` into one token.
                add_path(close_options_prefix, '{"label":', review_first)

            review_starts = [review_first] + [state() for _ in labels[1:]]
            for index, (label, review_start) in enumerate(zip(labels, review_starts)):
                reason_empty, reason_ends = bounded_string_states(required=True, max_tokens=64)
                for assessment in ("selected", "rejected"):
                    add_path(review_start, json.dumps(label) + ',"assessment":' + json.dumps(assessment) + ',"reason":"', reason_empty)
                if index + 1 < len(labels):
                    add_path_from_many(reason_ends, '"},{"label":', review_starts[index + 1])
                else:
                    add_path_from_many(reason_ends, '"}],"confidence":', confidence_start)
            for confidence in ("0", "0.25", "0.5", "0.75", "0.9", "1"):
                add_path(confidence_start, confidence + "}", self._schema_complete_state)
        elif self.schema_mode == "solver_code":
            code_empty, code_filled = required_string_states()
            add_path(0, '{"op":"submit_code","code":"', code_empty)
            add_path(code_filled, '"}', self._schema_complete_state)
        elif self.schema_mode == "solver_evidence":
            citations = tuple(dict.fromkeys(self.allowed_citation_refs))
            if len(citations) < 2:
                raise ValueError("evidence Solver schema requires at least two visible citation references")
            answer_empty, answer_filled = required_string_states()
            bridge_empty, bridge_filled = required_string_states()
            citation_start = state()
            citation_one = state()
            citation_many = state()
            reasoning_empty, reasoning_filled = required_string_states()
            add_path(0, '{"op":"answer_with_evidence","answer":"', answer_empty)
            add_path(answer_filled, '","bridge_entity":"', bridge_empty)
            add_path(bridge_filled, '","citations":[', citation_start)
            for citation in citations:
                literal = json.dumps(citation, ensure_ascii=False)
                add_path(citation_start, literal, citation_one)
                add_path(citation_one, "," + literal, citation_many)
                add_path(citation_many, "," + literal, citation_many)
            add_path(citation_many, '],"reasoning":["', reasoning_empty)
            add_path(reasoning_filled, '","', reasoning_empty)
            add_path(reasoning_filled, '"]}', self._schema_complete_state)
        elif self.schema_mode == "solver_repair":
            citations = tuple(dict.fromkeys(self.allowed_citation_refs))
            repair_actions = set(self.allowed_repair_actions or (
                "STOP", "ADD_EVIDENCE", "REPLACE_EVIDENCE", "PATCH_CITATIONS", "PATCH_BRIDGE", "REVISE_ANSWER"
            ))
            citation_start = state()
            citation_many = state()
            bridge_empty, bridge_filled = required_string_states()
            answer_empty, answer_filled = required_string_states()
            reasoning_empty, reasoning_filled = required_string_states()
            if "STOP" in repair_actions:
                add_path(0, '{"op":"repair_patch","action":"STOP","patch":{}}', self._schema_complete_state)
            for action_name in ("ADD_EVIDENCE", "REPLACE_EVIDENCE", "PATCH_CITATIONS"):
                if action_name not in repair_actions:
                    continue
                add_path(
                    0,
                    '{"op":"repair_patch","action":"' + action_name + '","patch":{"selected_fact_ids":[',
                    citation_start,
                )
            for citation in citations:
                literal = json.dumps(citation, ensure_ascii=False)
                add_path(citation_start, literal, citation_many)
                add_path(citation_many, "," + literal, citation_many)
            add_path(citation_many, '],"preserve_answer":true,"reasoning_chain":["', reasoning_empty)
            if "PATCH_BRIDGE" in repair_actions:
                add_path(0, '{"op":"repair_patch","action":"PATCH_BRIDGE","patch":{"bridge_entity":"', bridge_empty)
                add_path(bridge_filled, '","preserve_answer":true,"reasoning_chain":["', reasoning_empty)
            if "REVISE_ANSWER" in repair_actions:
                add_path(0, '{"op":"repair_patch","action":"REVISE_ANSWER","patch":{"answer":"', answer_empty)
                add_path(answer_filled, '","reasoning_chain":["', reasoning_empty)
            add_path(reasoning_filled, '","', reasoning_empty)
            add_path(reasoning_filled, '"]}}', self._schema_complete_state)
        elif self.schema_mode == "critic_numeric":
            reason_start, reason_ends = bounded_string_states(required=True, max_tokens=48)
            repair_start, repair_ends = bounded_string_states(required=True, max_tokens=48)
            consistent_reason, consistent_reason_ends = bounded_string_states(required=True, max_tokens=32)
            add_path(
                0,
                '{"op":"judge_numeric","model_verdict":"consistent","error_type":"none",'
                '"error_location":"","reason":"',
                consistent_reason,
            )
            add_path_from_many(consistent_reason_ends, '","repair_instruction":""}', self._schema_complete_state)
            for error_type in ("arithmetic", "wrong_operation", "missing_operand", "unit_mismatch"):
                for location in ("expression", "value", "grounding"):
                    add_path(
                        0,
                        '{"op":"judge_numeric","model_verdict":"inconsistent","error_type":'
                        + json.dumps(error_type) + ',"error_location":' + json.dumps(location) + ',"reason":"',
                        reason_start,
                    )
            add_path_from_many(reason_ends, '","repair_instruction":"', repair_start)
            add_path_from_many(repair_ends, '"}', self._schema_complete_state)
            uncertain_reason, uncertain_reason_ends = bounded_string_states(required=True, max_tokens=48)
            add_path(
                0,
                '{"op":"judge_numeric","model_verdict":"uncertain","error_type":"insufficient_context",'
                '"error_location":"grounding","reason":"',
                uncertain_reason,
            )
            add_path_from_many(uncertain_reason_ends, '","repair_instruction":""}', self._schema_complete_state)
        elif self.schema_mode == "critic_audit_choice":
            labels = tuple(dict.fromkeys(self.allowed_choice_labels))
            if not labels:
                raise ValueError("multiple-choice Critic schema requires visible choice labels")
            required_slots = tuple(self.required_audit_claim_ids) or tuple(str(item) for item in self.required_audit_slots) or ("slot:1",)
            required_options = tuple(self.required_audit_elimination_claim_ids) or tuple(str(item) for item in self.required_audit_options) or tuple(labels)
            candidate_version = self.required_candidate_version or "result@v1"
            manifest_digest = self.required_manifest_digest or "manifest-digest"
            def string_field(start: int, prefix: str, *, max_tokens: int = 64) -> int:
                content, ends = bounded_string_states(required=True, max_tokens=max_tokens)
                if prefix:
                    add_path(start, prefix, content)
                else:
                    self._schema_transitions.setdefault(start, {}).update(self._schema_transitions.get(content, {}))
                    self._schema_free_modes[start] = self._schema_free_modes.get(content, "required_empty")
                    self._schema_space_destinations[start] = self._schema_space_destinations.get(content, content)
                    self._schema_nonspace_destinations[start] = self._schema_nonspace_destinations.get(content, content)
                    self._schema_safe_destinations[start] = self._schema_safe_destinations.get(content, content)
                close = state()
                add_path_from_many(ends, '"', close)
                return close

            def enum_field(start: int, prefix: str, values: tuple[str, ...]) -> int:
                target = state()
                for value in values:
                    add_path(start, json.dumps(value) + prefix, target)
                return target

            slot_starts = [state() for _ in required_slots]
            add_path(0, '{"op":"audit_choice","candidate_version":' + json.dumps(candidate_version)
                     + ',"manifest_digest":' + json.dumps(manifest_digest)
                     + ',"slot_checks":[{"claim_id":' + json.dumps(required_slots[0]) + ',"assessment":', slot_starts[0])
            for index, start in enumerate(slot_starts):
                reason_start = state()
                for assessment in ("fits", "violates", "unknown"):
                    add_path(start, json.dumps(assessment) + ',"reason":"', reason_start)
                audit_reason_close = string_field(reason_start, '')
                if index + 1 < len(required_slots):
                    add_path(audit_reason_close, '},{"claim_id":' + json.dumps(required_slots[index + 1]) + ',"assessment":', slot_starts[index + 1])
                else:
                    options_start = state()
                    add_path(audit_reason_close, '}],"option_checks":[{"claim_id":' + json.dumps(required_options[0]) + ',"assessment":', options_start)

            option_starts = [options_start, *(state() for _ in required_options[1:])]
            for index, start in enumerate(option_starts):
                reason_start = state()
                for assessment in ("fits", "violates", "unknown"):
                    add_path(start, json.dumps(assessment) + ',"reason":"', reason_start)
                audit_reason_close = string_field(reason_start, '')
                if index + 1 < len(required_options):
                    add_path(audit_reason_close, '},{"claim_id":' + json.dumps(required_options[index + 1]) + ',"assessment":', option_starts[index + 1])
                else:
                    selected_start = state()
                    add_path(audit_reason_close, '}],"selected_option_check":{"assessment":', selected_start)

            selected_reason_start = state()
            for assessment in ("fits", "violates", "unknown"):
                add_path(selected_start, json.dumps(assessment) + ',"reason":"', selected_reason_start)
            selected_reason_close = string_field(selected_reason_start, '')
            summary_start, summary_ends = bounded_string_states(required=True, max_tokens=64)
            add_path(selected_reason_close, '},"summary":"', summary_start)
            add_string_close(summary_ends, self._schema_complete_state)
        elif self.schema_mode == "critic_code":
            diagnosis_start, diagnosis_ends = bounded_string_states(required=True, max_tokens=64)
            repair_start, repair_ends = bounded_string_states(required=False, max_tokens=64)
            add_path(0, '{"op":"diagnose_code","diagnosis":"', diagnosis_start)
            add_path_from_many(diagnosis_ends, '","repair_instruction":"', repair_start)
            add_path_from_many(repair_ends, '"}', self._schema_complete_state)
        elif self.schema_mode == "critic_evidence":
            reason_start, reason_ends = bounded_string_states(required=True, max_tokens=64)
            supported = (
                '{"op":"judge_evidence","answer_support":"supported","bridge_status":"valid",'
                '"citation_status":"valid","repair_target":"none","reason":"'
            )
            add_path(0, supported, reason_start)
            for answer_support in ("unsupported", "contradicted", "uncertain"):
                for bridge_status in ("valid", "invalid", "missing", "uncertain"):
                    for citation_status in ("valid", "invalid_citation", "missing_hop", "insufficient"):
                        for repair_target in ("answer", "bridge_entity", "cited_fact_ids"):
                            add_path(
                                0,
                                '{"op":"judge_evidence","answer_support":' + json.dumps(answer_support)
                                + ',"bridge_status":' + json.dumps(bridge_status)
                                + ',"citation_status":' + json.dumps(citation_status)
                                + ',"repair_target":' + json.dumps(repair_target) + ',"reason":"',
                                reason_start,
                            )
            add_path_from_many(reason_ends, '"}', self._schema_complete_state)
        else:  # pragma: no cover - construction rejects unknown modes
            raise ValueError(f"unknown semantic schema mode: {self.schema_mode}")

        # Reuse the tokenizer-wide JSON-string token classification populated
        # by Planner, or build it once when another role is constrained first.
        cached = getattr(tokenizer, "_planner_json_safe_token_cache", None)
        if cached is None:
            special_ids = set(int(item) for item in getattr(tokenizer, "all_special_ids", ()) or ())
            safe: set[int] = set()
            nonspace: set[int] = set()
            for token_id in range(len(tokenizer)):
                if token_id in special_ids:
                    continue
                try:
                    piece = tokenizer.decode([token_id], skip_special_tokens=False, clean_up_tokenization_spaces=False)
                except TypeError:
                    piece = tokenizer.decode([token_id])
                if not piece or "\ufffd" in piece or '"' in piece or "\\" in piece or any(ord(char) < 0x20 for char in piece):
                    continue
                safe.add(token_id)
                if piece.strip():
                    nonspace.add(token_id)
            cached = (frozenset(safe), frozenset(nonspace))
            try:
                setattr(tokenizer, "_planner_json_safe_token_cache", cached)
            except (AttributeError, TypeError):
                pass
        self._safe_string_token_ids, self._nonspace_string_token_ids = cached

    def _planner_states(self, generated_token_ids: Iterable[int]) -> frozenset[int]:
        generated = tuple(int(item) for item in generated_token_ids)
        cached = self._schema_prefix_cache.get(generated)
        if cached is not None:
            return cached
        # Replay iteratively so long JSON actions do not hit Python's recursion
        # limit (the previous recursive implementation failed on character
        # tokenizers and large all-option audits).
        states = frozenset({self._schema_start_state})
        prefix: tuple[int, ...] = ()
        for token_id in generated:
            prefix += (token_id,)
            prefix_cached = self._schema_prefix_cache.get(prefix)
            if prefix_cached is not None:
                states = prefix_cached
                continue
            destinations: set[int] = set()
            for current_state in states:
                destinations.update(self._schema_transitions.get(current_state, {}).get(token_id, ()))
                mode = self._schema_free_modes.get(current_state, "")
                if token_id in self._safe_string_token_ids and mode:
                    if mode == "required_empty":
                        if token_id in self._nonspace_string_token_ids:
                            destination = self._schema_nonspace_destinations.get(current_state)
                        else:
                            destination = self._schema_space_destinations.get(current_state, current_state)
                    else:
                        destination = self._schema_safe_destinations.get(current_state, current_state)
                    if destination is not None:
                        destinations.add(destination)
            states = frozenset(destinations)
            self._schema_prefix_cache[prefix] = states
        return states

    def _planner_allowed_tokens(self, states: Iterable[int]) -> set[int]:
        allowed: set[int] = set()
        for state in states:
            allowed.update(self._schema_transitions.get(state, {}))
            if state in self._schema_free_modes:
                allowed.update(self._safe_string_token_ids)
        return allowed

    @staticmethod
    def _encode(tokenizer: Any, text: str) -> list[int]:
        encoded = tokenizer(text, add_special_tokens=False)
        ids = encoded["input_ids"] if isinstance(encoded, Mapping) else encoded.input_ids
        if hasattr(ids, "tolist"):
            ids = ids.tolist()
        if ids and isinstance(ids[0], list):
            ids = ids[0]
        return [int(item) for item in ids]

    def is_complete(self, generated_token_ids: Iterable[int]) -> bool:
        generated = tuple(int(item) for item in generated_token_ids)
        if (
            self.schema_mode == "planner_plan"
            or self.schema_mode.startswith("solver_")
            or self.schema_mode.startswith("critic_")
        ):
            return self._schema_complete_state in self._planner_states(generated)
        if self.fixed_actions:
            return generated in self._operation_paths
        return bool(self._done_path) and generated == self._done_path

    def mask_logits(self, logits: Any, generated_token_ids: Iterable[int]) -> Any:
        """Mask the next token to a compatible grammar token.

        Full Schema decoding fails closed on an invalid prefix. Legacy
        operation-prefix constraints release logits after their prefix.
        """
        if (
            self.schema_mode == "planner_plan"
            or self.schema_mode.startswith("solver_")
            or self.schema_mode.startswith("critic_")
        ):
            states = self._planner_states(generated_token_ids)
            if self._schema_complete_state in states:
                return logits
            allowed_ids = self._planner_allowed_tokens(states)
            if not allowed_ids:
                raise RuntimeError("Action schema decoder reached an invalid token prefix")
            masked = logits.clone()
            masked[...] = -self._negative_infinity(masked)
            valid_ids = [token_id for token_id in allowed_ids if 0 <= token_id < masked.shape[-1]]
            masked[..., valid_ids] = logits[..., valid_ids]
            return masked
        if not self._operation_paths:
            return logits
        generated = tuple(int(item) for item in generated_token_ids)
        compatible = [path for path in self._operation_paths if path[: len(generated)] == generated]
        if not compatible or any(len(path) == len(generated) for path in compatible):
            return logits
        next_ids = {path[len(generated)] for path in compatible if len(path) > len(generated)}
        if not next_ids:
            return logits
        masked = logits.clone()
        masked[...] = -self._negative_infinity(masked)
        for token_id in next_ids:
            if 0 <= token_id < masked.shape[-1]:
                masked[..., token_id] = logits[..., token_id]
        return masked

    @staticmethod
    def _negative_infinity(logits: Any) -> Any:
        # torch tensors expose finfo through their dtype; keeping this generic
        # allows graph-only tests to use a lightweight tensor substitute.
        try:
            import torch

            return torch.inf
        except ImportError:  # pragma: no cover
            return float("inf")


def build_action_constraint(
    *,
    role: str,
    task_type: str,
    missing: Iterable[str],
    allowed_source_refs: Iterable[str] = (),
    allowed_choice_labels: Iterable[str] = (),
    allowed_citation_refs: Iterable[str] = (),
    allowed_repair_actions: Iterable[str] = (),
    required_audit_slots: Iterable[int] = (),
    required_audit_options: Iterable[str] = (),
    required_audit_claim_ids: Iterable[str] = (),
    required_audit_elimination_claim_ids: Iterable[str] = (),
    required_candidate_version: str = "",
    required_manifest_digest: str = "",
    forbidden_choice_labels: Iterable[str] = (),
    required_solver_slots: Iterable[int] = (),
    protocol_mode: str = "semantic_delta_v2",
) -> ActionConstraint:
    """Build the sole v2 legal action schema from the graph boundary."""
    if protocol_mode != "semantic_delta_v2":
        raise ValueError(f"unsupported action protocol: {protocol_mode}")
    missing_set = set(missing)
    if role not in {"planner", "solver", "critic"}:
        raise ValueError(f"no model-facing action constraint for role: {role}")
    if missing_set:
        allowed = model_semantic_ops(role, task_type)
        reason = "Semantic Delta requires the domain's typed semantic action"
    else:
        allowed, reason = ("done",), "stage boundary is complete"
    schema_mode = ""
    if role == "planner" and allowed == ("plan",):
        schema_mode = "planner_plan"
    elif role == "solver" and allowed:
        schema_mode = {
            "solve_numeric": "solver_numeric",
            "choose_option": "solver_choice",
            "submit_code": "solver_code",
            "answer_with_evidence": "solver_evidence",
        }.get(allowed[0], "")
    elif role == "critic" and allowed:
        schema_mode = {
            "judge_numeric": "critic_numeric",
            "audit_choice": "critic_audit_choice",
            "diagnose_code": "critic_code",
            "judge_evidence": "critic_evidence",
        }.get(allowed[0], "")
    return ActionConstraint(
        role=role,
        task_type=task_type,
        allowed_ops=tuple(allowed),
        reason=reason,
        required_fact_ids=(),
        fixed_actions=(),
        schema_mode=schema_mode,
        allowed_source_refs=tuple(dict.fromkeys(str(item) for item in allowed_source_refs if str(item))),
        allowed_choice_labels=tuple(dict.fromkeys(str(item) for item in allowed_choice_labels if str(item))),
        allowed_citation_refs=tuple(dict.fromkeys(str(item) for item in allowed_citation_refs if str(item))),
        allowed_repair_actions=tuple(dict.fromkeys(str(item) for item in allowed_repair_actions if str(item))),
        required_audit_slots=tuple(dict.fromkeys(int(item) for item in required_audit_slots)),
        required_audit_options=tuple(dict.fromkeys(str(item).strip().upper() for item in required_audit_options if str(item).strip())),
        required_audit_claim_ids=tuple(dict.fromkeys(str(item) for item in required_audit_claim_ids if str(item))),
        required_audit_elimination_claim_ids=tuple(dict.fromkeys(str(item) for item in required_audit_elimination_claim_ids if str(item))),
        required_candidate_version=str(required_candidate_version or ""),
        required_manifest_digest=str(required_manifest_digest or ""),
        forbidden_choice_labels=tuple(dict.fromkeys(str(item).strip().upper() for item in forbidden_choice_labels if str(item).strip())),
        required_solver_slots=tuple(dict.fromkeys(int(item) for item in required_solver_slots)),
    )
